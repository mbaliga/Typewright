"""Embed THIRD_PARTY.md in the app so About & licences (S23) shows every notice.

Writes ui/src/commonMain/kotlin/com/asoc/typewright/ui/settings/NoticeData.kt from THIRD_PARTY.md:
one section per "## " heading, its paragraphs and table rows as lines. Never hand-edit the output.
`--check` exits 1 when the checked-in file is out of date, which CI runs.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "THIRD_PARTY.md"
OUT = ROOT / "ui/src/commonMain/kotlin/com/asoc/typewright/ui/settings/NoticeData.kt"


def kotlin_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def sections():
    current = None
    out = []
    paragraph = []

    def flush():
        nonlocal paragraph
        if paragraph and current is not None:
            current[1].append(" ".join(paragraph))
        paragraph = []

    for raw in SRC.read_text().splitlines():
        line = raw.rstrip()
        if line.startswith("## "):
            flush()
            current = (line[3:].strip(), [])
            out.append(current)
        elif line.startswith("# ") or current is None:
            continue
        elif not line.strip():
            flush()
        elif re.fullmatch(r"\|[\s\-:|]+\|", line.strip()):
            continue
        elif line.strip().startswith("|"):
            flush()
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            current[1].append(" — ".join(c for c in cells if c))
        else:
            paragraph.append(re.sub(r"\s+", " ", line.strip()))
    flush()
    return out


def render() -> str:
    lines = [
        "// SPDX-License-Identifier: FSL-1.1-ALv2",
        "",
        "// Generated by tools/gen_notices.py from THIRD_PARTY.md. Do not edit by hand.",
        "package com.asoc.typewright.ui.settings",
        "",
        "/** One heading of THIRD_PARTY.md and its lines, as About & licences shows them. */",
        "data class NoticeSection(",
        "    val title: String,",
        "    val lines: List<String>,",
        ")",
        "",
        "/** Every notice in THIRD_PARTY.md, in its order. */",
        "val NOTICE_SECTIONS: List<NoticeSection> =",
        "    listOf(",
    ]
    for title, body in sections():
        lines.append("        NoticeSection(")
        lines.append(f"            {kotlin_string(title)},")
        lines.append("            listOf(")
        for b in body:
            chunks = [b[i : i + 90] for i in range(0, len(b), 90)] or [""]
            for k, chunk in enumerate(chunks):
                last = k == len(chunks) - 1
                indent = " " * (16 if k == 0 else 20)
                lines.append(f"{indent}{kotlin_string(chunk)}{',' if last else ' +'}")
        lines.append("            ),")
        lines.append("        ),")
    lines.append("    )")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("NoticeData.kt is out of date: run python3 tools/gen_notices.py")
            return 1
        print("NoticeData.kt is up to date with THIRD_PARTY.md.")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} bytes)")
    return 0


sys.exit(main())
