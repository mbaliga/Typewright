"""Write the app's version constant from version.properties, the one version file.

Gradle reads version.properties itself (app-android's versionName and versionCode, app-desktop's
package version). Common Kotlin cannot read a file at run time on every target, so About's
`APP_VERSION` is generated into ui/src/commonMain/.../settings/AppVersion.kt. `--check` exits 1 when
the checked-in file is out of date; CI runs it.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "version.properties"
OUT = ROOT / "ui/src/commonMain/kotlin/com/asoc/typewright/ui/settings/AppVersion.kt"


def read_properties() -> dict:
    values = {}
    for raw in SRC.read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip()
    return values


def render(values: dict) -> str:
    name = values.get("VERSION_NAME", "")
    code = values.get("VERSION_CODE", "")
    if not re.fullmatch(r"\d+\.\d+\.\d+(-rc\d+)?", name):
        sys.exit(f"version.properties: VERSION_NAME '{name}' is not MAJOR.MINOR.PATCH with an optional -rcN")
    if not re.fullmatch(r"[1-9]\d*", code):
        sys.exit(f"version.properties: VERSION_CODE '{code}' is not a positive integer")
    return (
        "// SPDX-License-Identifier: FSL-1.1-ALv2\n"
        "\n"
        "// Generated by tools/sync_version.py from version.properties. Do not edit by hand.\n"
        "package com.asoc.typewright.ui.settings\n"
        "\n"
        "/** The app's version, as the About screen, the crash report and the project screen show it. */\n"
        f'const val APP_VERSION: String = "{name}"\n'
        "\n"
        "/** Android's integer version, from the same file; shown beside the version in About's copied text. */\n"
        f"const val APP_VERSION_CODE: Int = {code}\n"
    )


def main() -> None:
    wanted = render(read_properties())
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != wanted:
            print("AppVersion.kt is out of date: run python3 tools/sync_version.py")
            sys.exit(1)
        print("AppVersion.kt matches version.properties.")
        return
    OUT.write_text(wanted)
    print(f"Wrote {OUT.relative_to(ROOT)}")


main()
