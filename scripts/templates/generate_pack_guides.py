"""Generate scripts/templates/pack-guides.json and the Kotlin literal
scripts/src/commonMain/kotlin/com/asoc/typewright/scripts/sheets/PackGuidesData.kt from the metric guide lines
drawn into every template of hyle-all-templates.zip, so the printable sheets draw exactly the guides the SVG pack
does (same lines, same names, same advance width) rather than a copy typed by hand.

For each printable script (Latin; Kana = Hiragana + Katakana; Devanagari; Naskh) it reads every template's
horizontal guide lines and their printed labels ("baseline 0", "x-height 500", ...), and the two vertical advance
lines, and fails if the templates of one script do not all carry the same guides. Lines at the same height are one
guide whose label joins theirs ("cap 700 / ascender 700").

Usage: python3 generate_pack_guides.py [--zip ./hyle-all-templates.zip]
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_ZIP = HERE / "hyle-all-templates.zip"
DEFAULT_JSON = HERE / "pack-guides.json"
DEFAULT_KOTLIN = HERE.parent / "src/commonMain/kotlin/com/asoc/typewright/scripts/sheets/PackGuidesData.kt"

SCRIPTS = {
    "LATIN": ["svg/Latin"],
    "KANA": ["svg/Hiragana", "svg/Katakana"],
    "DEVANAGARI": ["svg/Devanagari"],
    "NASKH": ["svg/Naskh"],
}

LINE = re.compile(r'<line x1="(-?\d+)" y1="(-?\d+)" x2="(-?\d+)" y2="(-?\d+)" stroke="#(c0392b|2980b9)" stroke-width="(\d+)"')
LABEL = re.compile(r'<text x="-134" y="(-?\d+)"[^>]*fill="#c0392b"[^>]*>([^<]*)</text>')


def guides_of(svg: str) -> dict:
    horizontal: dict[int, dict] = {}
    labels: dict[int, list[str]] = {}
    for y, text in LABEL.findall(svg):
        labels.setdefault(int(y) + 8, []).append(text)
    for x1, y1, x2, y2, colour, width in LINE.findall(svg):
        if colour != "c0392b" or y1 != y2:
            continue
        y = -int(y1)  # SVG y is down; font y is up
        entry = horizontal.setdefault(y, {"y": y, "labels": [], "solid": int(width) >= 3})
        for label in labels.get(int(y1), []):
            if label not in entry["labels"]:
                entry["labels"].append(label)
    vertical = sorted({int(x1) for x1, y1, x2, y2, colour, width in LINE.findall(svg) if colour == "2980b9" and x1 == x2})
    lines = [{"y": g["y"], "label": " / ".join(g["labels"]), "solid": g["solid"]} for g in sorted(horizontal.values(), key=lambda g: g["y"])]
    return {"lines": lines, "advance": vertical}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--zip", default=str(DEFAULT_ZIP))
    parser.add_argument("--json", default=str(DEFAULT_JSON))
    parser.add_argument("--kotlin", default=str(DEFAULT_KOTLIN))
    args = parser.parse_args()

    result = {}
    with zipfile.ZipFile(args.zip) as z:
        for script, folders in SCRIPTS.items():
            seen = None
            for name in sorted(z.namelist()):
                if not name.endswith(".svg") or not any(name.startswith(f + "/") for f in folders):
                    continue
                g = guides_of(z.read(name).decode("utf-8"))
                if seen is None:
                    seen = g
                elif g != seen:
                    sys.exit(f"{name} has different guides from the rest of {script}: {g} against {seen}")
            if seen is None or len(seen["advance"]) != 2:
                sys.exit(f"{script}: no guides found")
            result[script] = seen
    Path(args.json).write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// GENERATED by scripts/templates/generate_pack_guides.py from hyle-all-templates.zip (see pack-guides.json beside it).",
        "// Do not edit by hand: change the generator and run it again.",
        "",
        "package com.asoc.typewright.scripts.sheets",
        "",
        "/** The metric guides each printable script's templates carry, exactly as the SVG pack draws them. */",
        "internal val PACK_GUIDES: Map<PrintScript, PackGuides> =",
        "    mapOf(",
    ]
    for script, g in result.items():
        out.append(f"        PrintScript.{script} to")
        out.append("            PackGuides(")
        out.append("                lines =")
        out.append("                    listOf(")
        for line in g["lines"]:
            solid = "true" if line["solid"] else "false"
            out.append(f'                        PackGuideLine({line["y"]}, "{line["label"]}", {solid}),')
        out.append("                    ),")
        out.append(f"                advanceLeft = {g['advance'][0]},")
        out.append(f"                advanceRight = {g['advance'][1]},")
        out.append("            ),")
    out += ["    )", ""]
    Path(args.kotlin).write_text("\n".join(out), encoding="utf-8")
    print(json.dumps(result)[:600])


if __name__ == "__main__":
    main()
