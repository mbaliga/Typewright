"""Generate scripts/templates/latin-manifest.json, and the Kotlin literal
scripts/src/commonMain/kotlin/com/asoc/typewright/scripts/latin/LatinTemplateData.kt, from the real
scripts/templates/hyle-all-templates.zip's own svg/Latin/ folder -- the same "checked-in generated
data with its generator beside it; never hand-edit" convention as the kana, Devanagari and Naskh
manifests beside this file.

Every entry is a real file of the pack: its codepoint is read from the "U+XXXX" line printed in the
template itself, its glyph name is the Adobe Glyph List name for that codepoint (the name a UFO and a
compiler expect: `ampersand`, `quotesingle`, `periodcentered`, `Eth`), and where the AGL has no name the
AGL's own `uniXXXX` form is used (U+20B9 and U+0237 -- no Adobe name exists for them). The script fails
rather than guess when the folder does not hold exactly the 120 templates HOW_TO_USE.md states, when two
templates share a codepoint, or when the templates' guide lines are not identical.

Needs fontTools for the AGL: pip install fonttools.

Usage: python3 generate_latin_manifest.py [--zip ./hyle-all-templates.zip]
Run from anywhere; paths default relative to this file.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import unicodedata
import zipfile
from pathlib import Path

try:
    from fontTools import agl
except ImportError:  # pragma: no cover - environment message
    sys.exit("generate_latin_manifest.py needs fontTools for the Adobe Glyph List: pip install fonttools")

HERE = Path(__file__).resolve().parent
DEFAULT_ZIP = HERE / "hyle-all-templates.zip"
DEFAULT_JSON = HERE / "latin-manifest.json"
DEFAULT_KOTLIN = HERE.parent / "src/commonMain/kotlin/com/asoc/typewright/scripts/latin/LatinTemplateData.kt"
FOLDER = "svg/Latin"
EXPECTED_COUNT = 120

LINE = re.compile(r'<line x1="(-?\d+)" y1="(-?\d+)" x2="(-?\d+)" y2="(-?\d+)"')
CODEPOINT = re.compile(r"U\+([0-9A-F]{4,6})")


def glyph_name(codepoint: int) -> str:
    name = agl.UV2AGL.get(codepoint)
    return name if name else "uni%04X" % codepoint


def guides_of(svg: str) -> dict:
    """The metric lines as font units: the SVG's y is down, so a line at y=-500 is x-height 500."""
    horizontal = sorted({-int(y1) for x1, y1, x2, y2 in LINE.findall(svg) if y1 == y2})
    vertical = sorted({int(x1) for x1, y1, x2, y2 in LINE.findall(svg) if x1 == x2})
    return {"horizontal": horizontal, "vertical": vertical}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--zip", default=str(DEFAULT_ZIP))
    parser.add_argument("--json", default=str(DEFAULT_JSON))
    parser.add_argument("--kotlin", default=str(DEFAULT_KOTLIN))
    args = parser.parse_args()

    archive = Path(args.zip)
    entries = []
    guides = None
    with zipfile.ZipFile(archive) as z:
        files = sorted(n for n in z.namelist() if n.startswith(FOLDER + "/") and n.endswith(".svg"))
        if len(files) != EXPECTED_COUNT:
            sys.exit(f"{FOLDER} holds {len(files)} templates, HOW_TO_USE.md says {EXPECTED_COUNT}")
        for index, name in enumerate(files):
            svg = z.read(name).decode("utf-8")
            match = CODEPOINT.search(svg)
            if not match:
                sys.exit(f"{name} prints no U+XXXX line")
            codepoint = int(match.group(1), 16)
            g = guides_of(svg)
            if guides is None:
                guides = g
            elif g != guides:
                sys.exit(f"{name} has different guide lines: {g} against {guides}")
            file_name = name.split("/")[-1]
            if int(file_name[:3]) != index:
                sys.exit(f"{file_name} is out of order at {index}")
            entries.append(
                {
                    "index": index,
                    "file": file_name,
                    "codepoint": "U+%04X" % codepoint,
                    "char": chr(codepoint),
                    "unicode_name": unicodedata.name(chr(codepoint)),
                    "glyph_name": glyph_name(codepoint),
                }
            )
    names = [e["glyph_name"] for e in entries]
    codepoints = [e["codepoint"] for e in entries]
    if len(set(names)) != len(names) or len(set(codepoints)) != len(codepoints):
        sys.exit("duplicate glyph names or codepoints in the Latin templates")

    manifest = {
        "source": "scripts/templates/hyle-all-templates.zip svg/Latin, generated by scripts/templates/generate_latin_manifest.py",
        "archive_sha256": hashlib.sha256(archive.read_bytes()).hexdigest(),
        "template_count": len(entries),
        "shared_guide_metrics": guides,
        "templates": entries,
    }
    Path(args.json).write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// GENERATED by scripts/templates/generate_latin_manifest.py from hyle-all-templates.zip's svg/Latin folder",
        "// (see latin-manifest.json beside it). Do not edit by hand: change the generator and run it again.",
        "",
        "package com.asoc.typewright.scripts.latin",
        "",
        "/** The 120 Latin templates in the pack's own order: glyph name (Adobe Glyph List), Unicode name, code point, file name. */",
        "internal val LATIN_TEMPLATES: List<LatinTemplate> =",
        "    listOf(",
    ]
    for e in entries:
        cp = int(e["codepoint"][2:], 16)
        lines.append(
            f'        LatinTemplate("{e["glyph_name"]}", "{e["unicode_name"]}", 0x{cp:04X}, "{e["file"]}"),'
        )
    lines += ["    )", ""]
    Path(args.kotlin).write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {args.json} and {args.kotlin}: {len(entries)} templates, guides {guides}")


if __name__ == "__main__":
    main()
