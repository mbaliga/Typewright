    @Test
    fun onlyJsonNumbersAreRead() {
        for (text in listOf("", "-", "+1", "1.", ".5", "01", "1e", "1e+", "0x10", "NaN", "Infinity", "1_000", " 1", "1 ", "--1", "1.5.2")) {
            assertNull(parseJsonDouble(text), "\"$text\" is not a JSON number")
        }
        assertEquals(1.0e-7, parseJsonDouble("1e-0000000000000000000007"))
        assertEquals(Double.POSITIVE_INFINITY, parseJsonDouble("1e99999999999999999999"))
        assertEquals(0.0, parseJsonDouble("1e-99999999999999999999"))
    }

    /**
     * A seeded run through 6,000 values: raw bit patterns, uniform values in [-10, 10) and
     * thousandths. Each spelling must read back exactly, and the CRC-32 of all the spellings,
     * one per line, is pinned to the value computed in Python from `repr` of the same SplitMix64
     * stream, so JVM, Wasm and the reference agree byte for byte.
     */
    @Test
    fun aSeededRunMatchesThePythonReferenceByteForByte() {
        val random = SplitMix64(0x5EED_2026_0925_0001L)
        val text = StringBuilder()
        var count = 0

        fun add(value: Double) {
            val spelling = formatDouble(value)
            assertEquals(value.toRawBits(), parseJsonDouble(spelling)!!.toRawBits(), "$spelling reads back")
            text.append(spelling).append('\n')
            count++
        }
        while (count < 3000) {
            val bits = random.next()
            if (((bits ushr 52) and 0x7FF) == 0x7FFL) continue
            add(Double.fromBits(bits))
        }
        repeat(2000) { add((random.next() ushr 11).toDouble() * TWO_TO_THE_MINUS_53 * 20.0 - 10.0) }
        repeat(1000) { add((random.next().toULong() % 10001u).toInt().minus(5000) / 1000.0) }
        assertEquals(6000, count)
        assertEquals(PYTHON_CRC, Crc32.of(text.toString().encodeToByteArray()))
    }

    @Test
    fun nonFiniteValuesHaveNoSpelling() {
        assertFailsWith<IllegalArgumentException> { formatDouble(Double.NaN) }
        assertFailsWith<IllegalArgumentException> { formatDouble(Double.NEGATIVE_INFINITY) }
    }

    /** Steele, Lea and Flood's SplitMix64: a tiny generator that is easy to repeat in any language. */
    private class SplitMix64(
        private var state: Long,
    ) {
        fun next(): Long {
            state += -0x61c8864680b583ebL
            var z = state
            z = (z xor (z ushr 30)) * -0x40a7b892e31b1a47L
            z = (z xor (z ushr 27)) * -0x6b2fb644ecceee15L
            return z xor (z ushr 31)
        }
    }

    private companion object {
        const val TWO_TO_THE_MINUS_53 = 1.0 / (1L shl 53)
        const val PYTHON_CRC = -1858451314
    }
