/**
 * [formatReal] and [parseRealOrNull] against Python's own `repr(float)` and `float(str)`, the
 * reference fontTools writes and reads with. This is commonTest, so it runs on the JVM and on Wasm:
 * a target whose text or reading drifts from Python's fails here.
 */
class RealTextTest {
    @Test
    fun formatsEdgeCasesAsPythonRepr() {
        val expected =
            listOf(
                0.0 to "0.0",
                -0.0 to "-0.0",
                1.0 to "1.0",
                0.1 to "0.1",
                -12.5 to "-12.5",
                0.0001 to "0.0001",
                1e-5 to "1e-05",
                1e15 to "1000000000000000.0",
                1e16 to "1e+16",
                1.52e23 to "1.52e+23", // Wasm's own toString gives 1.5200000000000002E23
                -57037124590350416.0 to "-5.703712459035042e+16", // and -57037124590350416.0 here
                9007199254740993.0 to "9007199254740992.0",
                Double.MIN_VALUE to "5e-324", // the JVM's own toString gives 4.9E-324
                2 * Double.MIN_VALUE to "1e-323",
                2.2250738585072014e-308 to "2.2250738585072014e-308", // the smallest normal
                2.225073858507201e-308 to "2.225073858507201e-308", // the largest subnormal
                Double.MAX_VALUE to "1.7976931348623157e+308",
                1024.0 to "1024.0",
                0.5 to "0.5",
                0.1 + 0.2 to "0.30000000000000004",
            )
        for ((value, text) in expected) assertEquals(text, formatReal(value), "formatReal($value)")
        assertFailsWith<IllegalArgumentException> { formatReal(Double.NaN) }
        assertFailsWith<IllegalArgumentException> { formatReal(Double.NEGATIVE_INFINITY) }
    }

    @Test
    fun formatsASampleOfDoublesAsPythonReprAndReadsThemBack() {
        // Python 3.11: 120 random bit patterns, 60 decimals of up to 8 places, 20 of n x 10^k.
        var checked = 0
        for (entry in PYTHON_REPR.split(';')) {
            val (bits, text) = entry.split(':')
            val value = Double.fromBits(bits.toLong())
            assertEquals(text, formatReal(value), "formatReal($value)")
            assertEquals(bits.toLong(), parseReal(text).toRawBits(), "parseReal($text)")
            checked++
        }
        assertEquals(200, checked)
    }

    @Test
    fun readsASampleOfDecimalsAsPythonFloatDoes() {
        // Python 3.11 float(): 80 mantissas of 1 to 17 digits at exponents -330 to 310, 40 decimals.
        var checked = 0
        for (entry in PYTHON_FLOAT.split(';')) {
            val (text, bits) = entry.split('=')
            assertEquals(bits.toLong(), parseReal(text).toRawBits(), "parseReal($text)")
            checked++
        }
        assertEquals(120, checked)
    }

    @Test
    fun readsEdgeCasesCorrectlyRounded() {
        val expected =
            listOf(
                "0.51307701" to 0.51307701, // Wasm's own toDouble reads this one unit in the last place high
                "3.99e-16" to 3.99e-16,
                "9007199254740993" to 9007199254740992.0, // a tie, to even
                "9007199254740995" to 9007199254740996.0,
                "1.00000000000000011102230246251565404236316680908203125" to 1.0, // exactly halfway, to even
                "1.00000000000000011102230246251565404236316680908203126" to 1.0000000000000002,
                "2.4703282292062328e-324" to Double.MIN_VALUE, // just above half the smallest subnormal
                "2.4703282292062327e-324" to 0.0, // just below
                "1.7976931348623158e308" to Double.MAX_VALUE,
                "1.7976931348623159e308" to Double.POSITIVE_INFINITY,
                "1e-400" to 0.0,
                "-1e400" to Double.NEGATIVE_INFINITY,
                ".5" to 0.5,
                "5." to 5.0,
                "+12.5e-1" to 1.25,
                "  0000123.4500E2 " to 12345.0,
                "-0" to -0.0,
                "1e23" to 1e23,
            )
        for ((text, value) in expected) {
            assertEquals(value.toRawBits(), parseReal(text).toRawBits(), "parseReal($text)")
        }
        assertTrue(parseReal("NaN").isNaN()) // not a decimal, so read by the platform as before
        assertNull(parseRealOrNull("twelve"))
        assertNull(parseRealOrNull("."))
        assertNull(parseRealOrNull("1e"))
        assertFailsWith<NumberFormatException> { parseReal("") }
    }

    @Test
    fun everyDoubleReadsBackFromWhatIsWritten() {
        // A fixed pseudo-random walk over all bit patterns, the same on every target.
        var state = 0x2545F4914F6CDD1DL
        var checked = 0
        while (checked < 20_000) {
            state = state xor (state shl 13)
            state = state xor (state ushr 7)
            state = state xor (state shl 17)
            val value = Double.fromBits(state)
            if (!value.isFinite()) continue
            val text = formatReal(value)
            assertEquals(value.toRawBits(), parseReal(text).toRawBits(), "$value written as $text")
            assertTrue(text.length <= 24, text)
            checked++
        }
    }

